async function main() {
  const MONTH = arg('month') || '2026-07';
  const [Y, M] = MONTH.split('-').map(Number);
  const monthLabel = `${MONTH_NAMES[M - 1]} ${Y}`;

  const select =
    'select=appointment_date,appointment_time,created_at,status,final_price,client_name,client_phone,qr_hash,barbers(name),services(name)';
  const all: Row[] = await sbFetch(`${select}&order=appointment_date.asc&limit=20000`);
  // Shop closures are booked as ordinary appointments; they are not turnos.
  const live = all.filter((r) => !isClosureRow(r));

  // --- calendar month
  const mo = live.filter((r) => r.appointment_date?.startsWith(MONTH));
  const closures = all.filter((r) => r.appointment_date?.startsWith(MONTH)).length - mo.length;
  const att = mo.filter(isAttended);
  const open = mo.filter(isOpen);
  const cancelled = mo.filter((r) => r.status === 'cancelled');
  const fact = revenue(mo);
  const ticket = att.length ? fact / att.length : 0;
  const openMoney = open.reduce((s, r) => s + (r.final_price || 0), 0);
  const clients = new Set(mo.map((r) => (r.client_phone || '').trim()).filter(Boolean)).size;

  // --- origin split
  const byOrigin: Record<Origin, Row[]> = { interno: [], vip: [], externo: [], 'sin-hash': [] };
  for (const r of mo) byOrigin[origin(r)].push(r);

  // --- working weeks
  const weeks = workingWeeks(MONTH).map((w) => {
    const rows = live.filter((r) => r.appointment_date >= w.from && r.appointment_date <= w.to);
    const days = new Set(rows.map((r) => r.appointment_date)).size || 1;
    const a = rows.filter(isAttended);
    const o = rows.filter(isOpen);
    return {
      ...w,
      rows,
      days,
      att: a.length,
      open: o.length,
      cancelled: rows.filter((r) => r.status === 'cancelled').length,
      total: rows.length,
      fact: revenue(rows),
      openMoney: o.reduce((s, r) => s + (r.final_price || 0), 0),
      ext: rows.filter((r) => origin(r) === 'externo').length,
    };
  });

  // --- unclosed days, worst first
  // Scoped to the CALENDAR month on purpose: the "sin cerrar" KPI above counts
  // the calendar month, and a headline that disagreed with it by a few turnos
  // (the working weeks reach into the next month) would read as a mistake.
  const openByDay: Record<string, Row[]> = {};
  for (const r of open) {
    (openByDay[r.appointment_date] = openByDay[r.appointment_date] || []).push(r);
  }
  const worstDays = Object.entries(openByDay)
    .map(([d, rows]) => {
      const dayRows = live.filter((r) => r.appointment_date === d);
      return {
        date: d,
        open: rows.length,
        total: dayRows.length,
        money: rows.reduce((s, r) => s + (r.final_price || 0), 0),
      };
    })
    .sort((a, b) => b.open - a.open);
  const openTotal = worstDays.reduce((s, d) => s + d.open, 0);
  const openTotalMoney = worstDays.reduce((s, d) => s + d.money, 0);

  // --- Saturdays
  const saturdays = [...new Set(live.map((r) => r.appointment_date))]
    .filter((d) => d >= weeks[0].from && d <= weeks[weeks.length - 1].to)
    .filter((d) => {
      const [y, m, dd] = d.split('-').map(Number);
      return new Date(y, m - 1, dd).getDay() === 6;
    })
    .sort()
    .map((d) => {
      const rows = live.filter((r) => r.appointment_date === d);
      return {
        date: d,
        total: rows.length,
        att: rows.filter(isAttended).length,
        open: rows.filter(isOpen).length,
        fact: revenue(rows),
      };
    });

  // --- online bookings by weekday of creation (app usage by clients)
  const extByDow = Array(7).fill(0);
  let extTotal = 0;
  for (const r of live) {
    if (origin(r) !== 'externo' || !r.created_at) continue;
    const d = new Date(r.created_at).toLocaleDateString('en-CA', { timeZone: 'America/Argentina/Buenos_Aires' });
    const [y, m, dd] = d.split('-').map(Number);
    extByDow[new Date(y, m - 1, dd).getDay()]++;
    extTotal++;
  }
  const bestDow = extByDow.indexOf(Math.max(...extByDow));

  // --- barbers
  const barbers = Object.entries(
    mo.reduce<Record<string, Row[]>>((acc, r) => {
      const n = r.barbers?.name || 'Sin asignar';
      (acc[n] = acc[n] || []).push(r);
      return acc;
    }, {})
  )
    .map(([name, rows]) => ({
      name,
      total: rows.length,
      att: rows.filter(isAttended).length,
      open: rows.filter(isOpen).length,
      fact: revenue(rows),
      ext: rows.filter((r) => origin(r) === 'externo').length,
    }))
    .sort((a, b) => b.fact - a.fact);

  const cancelByOrigin = (['externo', 'interno', 'vip'] as Origin[]).map((o) => {
    const rows = byOrigin[o];
    const c = rows.filter((r) => r.status === 'cancelled').length;
    return { origin: o, total: rows.length, cancelled: c, rate: rows.length ? (c / rows.length) * 100 : 0 };
  });

  const now = new Date();
  const stamp = `${now.getDate()}/${now.getMonth() + 1}/${now.getFullYear()}`;

  const html = render({
    monthLabel, mo, closures, att, open, cancelled, fact, ticket, openMoney, clients,
    byOrigin, weeks, worstDays, openTotal, openTotalMoney, saturdays, extByDow, extTotal,
    bestDow, barbers, cancelByOrigin, stamp,
  });

  mkdirSync(OUT_DIR, { recursive: true });
  const out = join(OUT_DIR, `il-barbiere-mensual-${MONTH}.html`);
  writeFileSync(out, html);
  console.log(`OK — ${monthLabel}: ${mo.length} turnos, ${money(fact)}, ${openTotal} sin cerrar`);
  console.log(`  → ${out}`);
}

