/** Grouped bar chart: one bar per week, split attended / open / cancelled. */
function stackedBars(
  items: { label: string; parts: { value: number; color: string }[]; total: number }[],
  width = 640,
  height = 210
): string {
  const pad = { t: 14, r: 8, b: 34, l: 8 };
  const max = Math.max(...items.map((i) => i.total), 1);
  const bw = (width - pad.l - pad.r) / items.length;
  const barW = Math.min(bw * 0.56, 62);
  const plotH = height - pad.t - pad.b;
  let svg = '';
  items.forEach((it, idx) => {
    const cx = pad.l + bw * idx + bw / 2;
    let y = pad.t + plotH;
    it.parts.forEach((p) => {
      const h = (p.value / max) * plotH;
      y -= h;
      if (h > 0.4)
        svg += `<rect x="${(cx - barW / 2).toFixed(1)}" y="${y.toFixed(1)}" width="${barW.toFixed(1)}" height="${h.toFixed(1)}" fill="${p.color}" rx="2"/>`;
    });
    svg += `<text x="${cx.toFixed(1)}" y="${(pad.t + plotH - (it.total / max) * plotH - 5).toFixed(1)}" text-anchor="middle" font-size="11" font-weight="700" fill="#e8e8e8">${it.total}</text>`;
    svg += `<text x="${cx.toFixed(1)}" y="${(height - 14).toFixed(1)}" text-anchor="middle" font-size="10" fill="#8a8a8a">${esc(it.label)}</text>`;
  });
  svg += `<line x1="${pad.l}" y1="${pad.t + plotH}" x2="${width - pad.r}" y2="${pad.t + plotH}" stroke="#2a2a2a" stroke-width="1"/>`;
  return `<svg viewBox="0 0 ${width} ${height}" width="100%" preserveAspectRatio="xMidYMid meet">${svg}</svg>`;
}

/** Simple line-ish column chart for a money series. */
function moneyBars(items: { label: string; value: number }[], width = 640, height = 190): string {
  const pad = { t: 22, r: 8, b: 34, l: 8 };
  const max = Math.max(...items.map((i) => i.value), 1);
  const bw = (width - pad.l - pad.r) / items.length;
  const barW = Math.min(bw * 0.5, 54);
  const plotH = height - pad.t - pad.b;
  let svg = '';
  items.forEach((it, idx) => {
    const cx = pad.l + bw * idx + bw / 2;
    const h = (it.value / max) * plotH;
    const y = pad.t + plotH - h;
    svg += `<rect x="${(cx - barW / 2).toFixed(1)}" y="${y.toFixed(1)}" width="${barW.toFixed(1)}" height="${h.toFixed(1)}" fill="#00d4ff" opacity="0.75" rx="2"/>`;
    svg += `<text x="${cx.toFixed(1)}" y="${(y - 6).toFixed(1)}" text-anchor="middle" font-size="10" font-weight="700" fill="#e8e8e8">${money(it.value)}</text>`;
    svg += `<text x="${cx.toFixed(1)}" y="${(height - 14).toFixed(1)}" text-anchor="middle" font-size="10" fill="#8a8a8a">${esc(it.label)}</text>`;
  });
  svg += `<line x1="${pad.l}" y1="${pad.t + plotH}" x2="${width - pad.r}" y2="${pad.t + plotH}" stroke="#2a2a2a" stroke-width="1"/>`;
  return `<svg viewBox="0 0 ${width} ${height}" width="100%" preserveAspectRatio="xMidYMid meet">${svg}</svg>`;
}

/** Same shape as moneyBars, but labels the bars with plain counts. */
function countBars(items: { label: string; value: number }[], highlight: number, width = 640, height = 190): string {
  const pad = { t: 22, r: 8, b: 34, l: 8 };
  const max = Math.max(...items.map((i) => i.value), 1);
  const bw = (width - pad.l - pad.r) / items.length;
  const barW = Math.min(bw * 0.5, 54);
  const plotH = height - pad.t - pad.b;
  let svg = '';
  items.forEach((it, idx) => {
    const cx = pad.l + bw * idx + bw / 2;
    const h = (it.value / max) * plotH;
    const y = pad.t + plotH - h;
    const on = idx === highlight;
    svg += `<rect x="${(cx - barW / 2).toFixed(1)}" y="${y.toFixed(1)}" width="${barW.toFixed(1)}" height="${h.toFixed(1)}" fill="${on ? '#00d4ff' : '#3b3b45'}" rx="2"/>`;
    svg += `<text x="${cx.toFixed(1)}" y="${(y - 6).toFixed(1)}" text-anchor="middle" font-size="11" font-weight="700" fill="${on ? '#00d4ff' : '#9a9aa2'}">${it.value}</text>`;
    svg += `<text x="${cx.toFixed(1)}" y="${(height - 14).toFixed(1)}" text-anchor="middle" font-size="10" fill="${on ? '#e8e8e8' : '#8a8a92'}">${esc(it.label)}</text>`;
  });
  svg += `<line x1="${pad.l}" y1="${pad.t + plotH}" x2="${width - pad.r}" y2="${pad.t + plotH}" stroke="#2a2a2a" stroke-width="1"/>`;
  return `<svg viewBox="0 0 ${width} ${height}" width="100%" preserveAspectRatio="xMidYMid meet">${svg}</svg>`;
}

/**
 * Horizontal 100% stacked bar for the origin split.
 *
 * Laid out in real user units with a uniform aspect ratio, NOT in percent with
 * preserveAspectRatio="none": a non-uniformly scaled viewBox stretches the
 * labels along with the rects and the percentages collide into each other.
 */
function splitBar(parts: { label: string; value: number; color: string }[], total: number): string {
  const W = 640, H = 34;
  let x = 0;
  let svg = '';
  for (const p of parts) {
    const w = (p.value / total) * W;
    if (w <= 0) continue;
    svg += `<rect x="${x.toFixed(1)}" y="0" width="${w.toFixed(1)}" height="${H}" fill="${p.color}"/>`;
    if (w > 42)
      svg += `<text x="${(x + w / 2).toFixed(1)}" y="22" text-anchor="middle" font-size="14" font-weight="700" fill="#07141a">${Math.round((p.value / total) * 100)}%</text>`;
    x += w;
  }
  return `<svg viewBox="0 0 ${W} ${H}" width="100%" preserveAspectRatio="xMidYMid meet">${svg}</svg>`;
}

