/**
 * Monthly report generator for IL BARBIERE OS — client-facing, PDF-oriented.
 *
 * Complements weekly-report.ts: same data source and visual identity, but cut
 * by month and written to be exported to PDF and sent to Santi & Fede.
 *
 * Two windows are reported side by side on purpose, because they answer
 * different questions and do NOT add up to the same totals:
 *   - Calendar month (1–31): the month as the calendar sees it.
 *   - Working weeks Tue–Sat (S1–S5): the month as the shop works it. The shop
 *     is closed Sun+Mon, so a week that ends on Sunday truncates Saturday and
 *     makes the last week look artificially weak.
 * Stating both, labelled, is deliberate — a reader who spots two different
 * totals with no explanation stops trusting every other number in the report.
 *
 * Charts are inline SVG, fonts are system fonts, and there is no JavaScript:
 * WeasyPrint renders no JS and fetches no network assets.
 *
 * Usage:
 *   bun scripts/monthly-report.ts                 # July 2026 (default)
 *   bun scripts/monthly-report.ts --month 2026-08
 *
 * Output: ~/Documents/Adriel-Core/02_BARBIERE-AS/informes-mensuales/
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';
import { homedir } from 'os';
import { isClosureRow } from '../src/shared/lib/closures';

const OUT_DIR = join(homedir(), 'Documents/Adriel-Core/02_BARBIERE-AS/informes-mensuales');
const MONTH_NAMES = [
  'enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio',
  'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre',
];
const DOW = ['Domingo', 'Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado'];
const DOW_SHORT = ['Dom', 'Lun', 'Mar', 'Mié', 'Jue', 'Vie', 'Sáb'];

type Row = {
  appointment_date: string;
  appointment_time: string | null;
  created_at: string;
  status: string;
  final_price: number | null;
  client_name: string | null;
  client_phone: string | null;
  qr_hash: string | null;
  barbers: { name: string } | null;
  services: { name: string } | null;
};

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? undefined : process.argv[i + 1];
}

function loadEnv(): Record<string, string> {
  const raw = readFileSync('.env.production.local', 'utf8');
  const env: Record<string, string> = {};
  for (const line of raw.split('\n')) {
    const t = line.trim();
    if (!t || t[0] === '#' || !t.includes('=')) continue;
    const i = t.indexOf('=');
    env[t.slice(0, i).trim()] = t.slice(i + 1).trim().replace(/^["']|["']$/g, '');
  }
  return env;
}

const env = loadEnv();

async function sbFetch(qs: string): Promise<any[]> {
  const url = `${env.NEXT_PUBLIC_SUPABASE_URL.replace(/\/$/, '')}/rest/v1/appointments?${qs}`;
  const res = await fetch(url, {
    headers: {
      apikey: env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
      Authorization: `Bearer ${env.NEXT_PUBLIC_SUPABASE_ANON_KEY}`,
    },
  });
  if (!res.ok) throw new Error(`Supabase ${res.status}: ${await res.text()}`);
  return res.json();
}

const money = (n: number) => '$' + Math.round(n).toLocaleString('es-AR');
const pct = (a: number, b: number) => (b ? Math.round((a / b) * 100) : 0);
const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * Booking origin, derived from the qr_hash prefix — the schema has no `source`
 * column, so the prefix written at insert time is the only discriminator.
 *   MANUAL- -> loaded by a barber in the admin (appointmentService / CalendarView)
 *   VIP-    -> generated by the fixed-weekly VIP generator
 *   other   -> booked online by the client (booking/Confirmation.tsx)
 */
type Origin = 'interno' | 'vip' | 'externo' | 'sin-hash';
function origin(r: { qr_hash: string | null }): Origin {
  const h = r.qr_hash || '';
  if (h.startsWith('MANUAL-')) return 'interno';
  if (h.startsWith('VIP-')) return 'vip';
  return h ? 'externo' : 'sin-hash';
}

const isAttended = (r: Row) => r.status === 'attended';
const isOpen = (r: Row) => r.status === 'confirmed'; // never closed as attended or cancelled
const revenue = (rows: Row[]) => rows.filter(isAttended).reduce((s, r) => s + (r.final_price || 0), 0);
const dayLabel = (iso: string) => {
  const [y, m, d] = iso.split('-').map(Number);
  return `${DOW_SHORT[new Date(y, m - 1, d).getDay()]} ${d}/${m}`;
};

/** Tue–Sat working weeks that cover the month, including a Saturday spilling into the next. */
function workingWeeks(month: string): { tag: string; from: string; to: string }[] {
  const [y, m] = month.split('-').map(Number);
  const iso = (d: Date) =>
    `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  const first = new Date(y, m - 1, 1);
  const last = new Date(y, m, 0);
  // Back up to the Tuesday of the week containing the 1st.
  const start = new Date(first);
  start.setDate(start.getDate() - ((start.getDay() + 5) % 7));
  const out: { tag: string; from: string; to: string }[] = [];
  let i = 1;
  for (let cur = new Date(start); cur <= last; cur.setDate(cur.getDate() + 7)) {
    const from = new Date(cur);
    const to = new Date(cur);
    to.setDate(to.getDate() + 4); // Tue + 4 = Sat
    out.push({ tag: `S${i++}`, from: iso(from), to: iso(to) });
  }
  return out;
}

